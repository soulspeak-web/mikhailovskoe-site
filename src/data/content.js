export const spaces = rows.map(
  ([slug, title, category, description, image], i) => {
    const project = projectSpaces.find(
      (p) => p.id === (slug === "main" ? "main-house" : slug),
    );
    
const galleryImages =
  slug === "main"
    ? (project?.gallery || []).slice(0, 2)
    : (project?.gallery || []);

const gallery = galleryImages.map((key) => {

      const item = spaceImages[key];
      return {
        src: item.image,
        title: item.title,
        caption:
          item.note ||
          (item.diagram
            ? "Проектная схема · материалы предзащиты"
            : "Из материалов проекта; атрибуция уточняется"),
        diagram: !!item.diagram,
        source: item.source,
      };
    });
    return {
      slug,
      title,
      category,
      
description: ["flicker", "rakurs", "spectrum", "obscura"].includes(slug)
  ? "Кинопоказы, лекции, дискуссии"
  : project?.summary || description,

      detail: project?.detail,
      location: project?.location,
      gallery,
      
      image:
        slug === "main"
          ? "02_Экстерьер.jpg"
          : slug === "wing"
            ? "Экстерьер Флигель (1).jpg"
            : slug === "park"
              ? "park.webp"
              : spaceLogos[slug] ?? null,

      imageNote:
        slug === "wing"
          ? "Проектная визуализация"
          : slug === "park"
            ? "Территория усадьбы"
            : slug === "main"
              ? "Существующее состояние"
              : null,
      number: String(i + 1).padStart(2, "0"),
    };
  },
);

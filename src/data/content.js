export const spaces = rows.map(
  ([slug, title, category, description, image], i) => {
    const project = projectSpaces.find(
      (p) => p.id === (slug === "main" ? "main-house" : slug),
    );
    const gallery = (project?.gallery || []).map((key) => {
      const item = spaceImages[key];
      return {
        src: item.image,
        title: item.title,
        caption:
          item.note ||
          (item.diagram
            ? "Проектная схема · материалы предзащиты"
            : "Из материалов проекта; атрибуция уточняется"),
        diagram: !!item.diagram,
        source: item.source,
      };
    });
    return {
      slug,
      title,
      category,
      description: project?.summary || description,
      detail: project?.detail,
      location: project?.location,
      gallery,
      image:
        slug === "main"
          ? "estate.webp"
          : slug === "wing"
            ? "wing-concept.webp"
            : slug === "park"
              ? "park.webp"
              : null,
      imageNote:
        slug === "wing"
          ? "Проектная визуализация"
          : slug === "park"
            ? "Территория усадьбы"
            : slug === "main"
              ? "Существующее состояние"
              : null,
      number: String(i + 1).padStart(2, "0"),
    };
  },
);
